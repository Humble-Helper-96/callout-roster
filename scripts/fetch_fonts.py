#!/usr/bin/env python3
"""Bundle the theme fonts so the app makes no outside calls at runtime.

Downloads the .woff2 files Google Fonts serves for Barlow, Barlow Condensed and
Share Tech Mono and writes app/static/fonts.css with @font-face rules pointing
at the local copies. Run once when setting up or upgrading the theme; the
result is committed. The fonts are licensed under the SIL Open Font License.
"""
from __future__ import annotations

import pathlib
import re
import sys
import urllib.request

CSS_URL = (
    "https://fonts.googleapis.com/css2?family=Barlow:wght@400;500;600"
    "&family=Barlow+Condensed:wght@600;700&family=Share+Tech+Mono&display=swap"
)
# A modern UA makes Google return woff2 sources with unicode-range subsets.
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "app" / "static" / "fonts"
OUT_CSS = ROOT / "app" / "static" / "fonts.css"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def main() -> int:
    css = fetch(CSS_URL).decode("utf-8")
    blocks = re.findall(r"@font-face\s*\{[^}]*\}", css)
    if not blocks:
        print("no @font-face blocks found", file=sys.stderr)
        return 1
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    out = ["/* Self-hosted theme fonts (SIL Open Font License). Generated by scripts/fetch_fonts.py */"]
    counters: dict[str, int] = {}
    for block in blocks:
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        src = re.search(r"url\((https://[^)]+)\)", block).group(1)
        key = f"{family.lower().replace(' ', '-')}-{weight}-{style}"
        counters[key] = counters.get(key, 0) + 1
        name = f"{key}-{counters[key]}.woff2"
        (FONT_DIR / name).write_bytes(fetch(src))
        out.append(re.sub(r"url\(https://[^)]+\)", f"url(./fonts/{name})", block))
        print("fetched", name)
    OUT_CSS.write_text("\n".join(out) + "\n", encoding="utf-8")
    (FONT_DIR / "LICENSE.txt").write_text(
        "Barlow, Barlow Condensed (Jeremy Tribby) and Share Tech Mono (Carrois Apostrophe)\n"
        "are licensed under the SIL Open Font License 1.1: https://openfontlicense.org/\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT_CSS.relative_to(ROOT)} with {len(blocks)} faces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
