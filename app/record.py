"""The official record of a callout, as a PDF.

TAK Server does not keep records long term, so this file is what gets filed:
who opened the callout and when, the brief and location, how it closed,
every team member's response with role, times and ETA, who recorded each
status, and the full event log.
"""
from __future__ import annotations

import json

from . import callouts as co
from .hooks import list_events
from .pdf import Document
from .roster import grouped_by_team, list_rows
from .timeutil import fmt_local_full, to_iso, utcnow
from .units import list_teams


def build_record(db, unit, callout, tz, generated_by: str) -> bytes:
    fmt = lambda iso: fmt_local_full(iso, tz) if iso else "-"
    doc = Document(f"{unit['name']} callout record #{callout['id']}")

    doc.line(unit["name"].upper(), size=11, font="bold")
    doc.line(f"CALLOUT RECORD - {callout['label']}", size=18, font="bold", gap=4)
    doc.line(f"Generated {fmt(to_iso(utcnow()))} by {generated_by}", size=9, gap=6)

    doc.heading("Callout")
    doc.kv("Label", callout["label"])
    doc.kv("Opened", f"{fmt(callout['opened_at'])} by {callout['opened_by']}")
    if callout["closed_at"]:
        how = "expired automatically" if callout["close_reason"] == "expired" else f"closed by {callout['closed_by']}"
        doc.kv("Closed", f"{fmt(callout['closed_at'])} ({how})")
    else:
        doc.kv("Status", f"ACTIVE at time of export; auto-closes {fmt(callout['expires_at'])}")
    if callout["lat"] is not None:
        loc = f"{callout['lat']:.6f}, {callout['lon']:.6f}"
        if callout["location_label"]:
            loc = f"{callout['location_label']} ({loc})"
        doc.kv("Location", loc)
    elif callout["location_label"]:
        doc.kv("Location", callout["location_label"])
    else:
        doc.kv("Location", "not recorded")

    doc.heading("Tactical brief")
    doc.line(callout["brief"] or "No brief recorded.", size=10, gap=2)

    counts = co.team_counts(db, callout["id"])
    doc.heading("Response summary")
    t = counts["total"]
    doc.line(f"{t['coming']} of {t['active']} active members acknowledged, en route or on scene.", size=10)
    doc.table(["Team", "Active", "Ack", "En route", "On scene", "Cleared", "Unavail"],
              [[b["name"], b["active"], b["acknowledged"], b["en_route"], b["on_scene"], b["cleared"], b["unavailable"]]
               for b in [*counts["teams"].values(), t]],
              [16, 6, 5, 8, 8, 7, 7])

    doc.heading("Responses by team")
    rows = [r for r in list_rows(db, unit["id"], active_only=False) if r["person_id"]]
    responses = co.responses_map(db, callout["id"])
    people_rows = [r for r in rows if r["active"] or r["id"] in responses]
    for team, members in grouped_by_team(people_rows, list_teams(db, unit["id"])):
        if not members:
            continue
        doc.space(4)
        doc.line(team["name"] if team else "Unassigned", size=11, font="bold", gap=2)
        table = []
        for r in members:
            resp = responses.get(r["id"])
            status = co.STATUSES[resp["status"]] if resp else co.STATUSES[co.DEFAULT_STATUS]
            first = fmt_local_full(resp["first_at"], tz)[11:16] if resp else ""
            last = fmt_local_full(resp["last_at"], tz)[11:16] if resp else ""
            eta = fmt_local_full(resp["eta_at"], tz)[11:16] if resp and resp["eta_at"] else ""
            by = "" if not resp or (resp["set_by"] or "").lower() == (r["tak_username"] or "").lower() else resp["set_by"]
            table.append([r["position"], r["name"], r["role"] or "", status, first, last, eta, by])
        doc.table(["Callsign", "Name", "Role", "Status", "First", "Last", "ETA", "Set by"], table,
                  [8, 20, 22, 13, 5, 5, 5, 9])

    doc.heading("Event log")
    log_rows = []
    for e in list_events(db, callout["id"]):
        detail = ""
        try:
            payload = json.loads(e["payload"])
            if e["type"] == "callout.response":
                resp = payload.get("response", {})
                detail = f"{resp.get('position', '')} -> {co.STATUSES.get(resp.get('status'), resp.get('status'))}"
                if resp.get("eta_at"):
                    detail += f" ETA {fmt_local_full(resp['eta_at'], tz)[11:16]}"
            elif e["type"] == "callout.extended":
                detail = f"+{payload.get('extended_hours')}h"
            elif e["type"] == "callout.closed":
                detail = payload.get("reason", "")
        except (ValueError, TypeError):
            pass
        log_rows.append([fmt_local_full(e["created_at"], tz), e["type"].replace("callout.", ""), e["actor"] or "", detail])
    doc.table(["Time", "Event", "By", "Detail"], log_rows, [22, 16, 12, 30])

    doc.space(10)
    doc.line("Times are shown in the unit's local time zone. Generated by Callout Roster.", size=8)
    return doc.render()
